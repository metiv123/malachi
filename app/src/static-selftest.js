import { readFile, readdir, stat } from 'node:fs/promises';
import path from 'node:path';

const publicDir = path.resolve(process.cwd(), 'public');

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

async function exists(target) {
  try { return (await stat(target)).isFile(); } catch { return false; }
}

async function run() {
  const files = await readdir(publicDir);
  const htmlFiles = files.filter((name) => name.endsWith('.html'));
  const jsFiles = files.filter((name) => name.endsWith('.js'));

  for (const filename of jsFiles) {
    const source = await readFile(path.join(publicDir, filename), 'utf8');
    new Function(source);
  }

  for (const filename of htmlFiles) {
    const html = await readFile(path.join(publicDir, filename), 'utf8');
    for (const match of html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi)) new Function(match[1]);
    const references = [...html.matchAll(/(?:href|src)="([^"]+)"/g)].map((match) => match[1]);
    for (const reference of references) {
      if (!reference.startsWith('/') || reference.startsWith('/api/')) continue;
      const clean = reference.split(/[?#]/)[0];
      // config.js is generated by the application server at runtime.
      if (clean === '/' || clean === '/config.js') continue;
      assert(await exists(path.join(publicDir, clean.replace(/^\//, ''))), `${filename}: missing local reference ${reference}`);
    }
  }

  const index = await readFile(path.join(publicDir, 'index.html'), 'utf8');
  assert((index.match(/חשוב לדעת/g) || []).length === 1, 'homepage must contain one combined important notice');
  assert(index.includes('class="nav-login"') && index.includes('/login.html'), 'top user-login button missing');
  assert(index.includes('/accessibility.html'), 'accessibility statement link missing');
  assert(index.includes('src="/analytics.js"'), 'Israeli homepage analytics missing');
  const englishIndex = await readFile(path.join(publicDir, 'en/index.html'), 'utf8');
  assert(englishIndex.includes('src="/analytics.js"'), 'UK homepage analytics missing');
  assert(englishIndex.includes('id="partnerReview"') && englishIndex.includes('partner-review') && englishIndex.includes('hidden'), 'UK partner-review panel must exist and stay hidden by default');
  assert(englishIndex.includes("partnerSource.startsWith('email_')") && englishIndex.includes("partnerCampaign.startsWith('uk_partner')"), 'UK partner-review source targeting missing');
  const adminPage = await readFile(path.join(publicDir, 'admin.html'), 'utf8');
  assert(adminPage.includes('sourceFunnels') && adminPage.includes('campaignFunnels') && adminPage.includes('משפך לפי מקור'), 'admin source and campaign funnel view missing');
  assert((await readFile(path.join(publicDir, 'create-user.html'), 'utf8')).includes('src="/analytics.js"'), 'Israeli signup analytics missing');
  assert((await readFile(path.join(publicDir, 'en/create-user.html'), 'utf8')).includes('src="/analytics.js"'), 'UK signup analytics missing');
  assert((await readFile(path.join(publicDir, 'f.html'), 'utf8')).includes('source=facebook'), 'Israeli Facebook short link missing');
  assert((await readFile(path.join(publicDir, 'w.html'), 'utf8')).includes('source=whatsapp'), 'Israeli WhatsApp short link missing');
  assert((await readFile(path.join(publicDir, 'en/f.html'), 'utf8')).includes('source=facebook'), 'UK Facebook short link missing');
  assert((await readFile(path.join(publicDir, 'en/w.html'), 'utf8')).includes('source=whatsapp'), 'UK WhatsApp short link missing');

  const customerFiles = ['dashboard.js', 'create-user.js', 'login.js', 'feedback.html'];
  for (const filename of customerFiles) {
    const source = await readFile(path.join(publicDir, filename), 'utf8');
    assert(!source.includes('malachi_management_token'), `${filename}: legacy localStorage token remains`);
    assert(!source.includes('dashboard.html?token='), `${filename}: token remains in dashboard URL`);
  }
  console.log('✅ public site selftest passed');
}

run().catch((error) => {
  console.error('❌ public site selftest failed:', error);
  process.exitCode = 1;
});
